def main() -> None:
    con = sqlite3.connect(DB)
    now = datetime.now(timezone.utc).isoformat()
    n = 0
    with con:
        for p in PROBLEMS:
            content = json.dumps(p, ensure_ascii=False, separators=(",", ":"))
            digest = sha256(content.encode()).hexdigest()
            cur = con.execute(
                "insert into learning_problems (creation_id, creation_hash, draft_json,"
                " draft_revision, published_revision, created_at) values (?,?,?,1,1,?)",
                (str(uuid.uuid4()), digest, content, now),
            )
            pid = cur.lastrowid
            con.execute(
                "insert into learning_versions (id, problem_id, revision, content_json, created_at)"
                " values (?,?,?,?,?)",
                (str(uuid.uuid4()), pid, 1, content, now),
            )
            n += 1
    print(f"写入 {n} 道基础语法题到 {DB}")


if __name__ == "__main__":
    main()
